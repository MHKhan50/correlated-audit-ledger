import csv, json, random, statistics
from pathlib import Path
from audit_ledger import make_episode, predict, metrics
ROOT=Path(__file__).resolve().parent; OUT=ROOT/'outputs'; OUT.mkdir(exist_ok=True)
rows=[]; summary=[]
missing_rates=[.05,.15,.30]; outage_rates=[0,.10,.25]; rules=[('strict_complete',.8),('optimistic_missing',.5),('score_threshold',.65),('score_threshold',.8)]
# Synthetic data split by seeds; tune threshold on train seeds only.
for mr in missing_rates:
 for orate in outage_rates:
  train=[make_episode(s*100000+i,mr,orate) for s in (11,22,33) for i in range(150)]
  candidates=[round(x/100,2) for x in range(30,101,5)]
  threshold=min(candidates,key=lambda t: metrics([e.true_gap for e in train],[int(e.evidence_score>=t) for e in train])['weighted_cost'])
  for seed in (44,55):
   eps=[make_episode(seed*100000+i,mr,orate) for i in range(250)]
   for idx,e in enumerate(eps):
    rows.append({'split':'test','seed':seed,'episode_id':f'{seed}-{idx}','missing_rate':mr,'shared_outage_rate':orate,'true_responsibility_gap':e.true_gap,'observed_evidence_score':round(e.evidence_score,6),'note':'synthetic simulation; no real LLM/production logs'})
   for name,t in rules+[('cost_tuned',threshold)]:
    m=metrics([e.true_gap for e in eps],[predict(e,name,t) if name!='cost_tuned' else int(e.evidence_score>=t) for e in eps])
    summary.append({'missing_rate':mr,'shared_outage_rate':orate,'seed':seed,'rule':name,'threshold':t,**m})
with (OUT/'synthetic_test_dataset.csv').open('w',newline='') as f:
 w=csv.DictWriter(f,fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)
with (OUT/'metrics_by_seed.csv').open('w',newline='') as f:
 w=csv.DictWriter(f,fieldnames=summary[0].keys()); w.writeheader(); w.writerows(summary)
# Aggregate summary across the two held-out seeds.
groups={}
for r in summary: groups.setdefault((r['missing_rate'],r['shared_outage_rate'],r['rule']),[]).append(r)
lines=['# Experiment summary','', 'Synthetic benchmark only; results are not evidence about real systems or LLMs. Test seeds: 44 and 55.','', '| Missing | Shared outage | Rule | F1 mean | Recall mean | FPR mean | Weighted cost mean |','|---:|---:|---|---:|---:|---:|---:|']
for (mr,orate,rule),rs in sorted(groups.items()):
 lines.append(f"| {mr:.2f} | {orate:.2f} | {rule} | {statistics.mean(x['f1'] for x in rs):.3f} | {statistics.mean(x['recall'] for x in rs):.3f} | {statistics.mean(x['fpr'] for x in rs):.3f} | {statistics.mean(x['weighted_cost'] for x in rs):.1f} |")
(OUT/'results_summary.md').write_text('\n'.join(lines)+'\n')
(OUT/'dataset_card.md').write_text('''# Dataset card\n\n`synthetic_test_dataset.csv` is generated by `run_experiment.py`. It contains simulated episode-level labels and observed evidence scores, across independent field-missingness and shared-agent-outage settings. It is not collected from real users, deployed systems, or LLMs. The data are deterministic for the fixed seeds in the script. Use for teaching and method prototyping only; do not make real-world safety claims from it.\n''')
print(f'Wrote {len(rows)} synthetic episodes and {len(summary)} metric rows to {OUT}')
